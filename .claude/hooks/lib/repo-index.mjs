// What a checkout already holds, per file: its element shapes, its statements and its definitions, kept between calls in the temp folder and read
// again only for a file whose time or size moved. template-law judges a write against it; reuse-hint shows it at the prompt.
//   repoIndex(root, skipGlobs, layout) -> { rel: { m, s, shapes: [[id, line, what]], st: [[hash, line]], defs: [[name, line]] } }
import { statSync } from 'node:fs';
import { extname, join } from 'node:path';
import { isContent } from './content.mjs';
import { MARKUP, codeFiles, shapesOf } from './elements.mjs';
import { readText } from './files.mjs';
import { tmpKeyed } from './hash.mjs';
import { readJson, writeJson } from './json.mjs';
import { ALL_CODE } from './languages.mjs';
import { definesOf, fingerprint } from './near-copies.mjs';
export const EXTS = new Set([...ALL_CODE, ...MARKUP]);
const GENERATED = /@generated\b|\b(?:auto-?generated|generated by|do not edit)\b/i;
// A `one-off:` line covers what follows it, down to the next blank line.
export function oneOffLines(text) {
    const out = new Set();
    let on = false;
    text.split('\n').forEach((l, i) => { on = /one-off:/.test(l) || (on && l.trim() !== ''); if (on)
        out.add(i + 1); });
    return out;
}
// One object set up twice is one object; a copy of a set-up has another receiver.
const distinct = (list) => list.filter((s, i) => s.kind !== 'setup' || list.findIndex((x) => x.id === s.id && x.what === s.what) === i);
// A declaration file states what another file defines, and a probe script under docs/ is a throwaway beside the code it probes: neither is a
// second definition of anything (KWB-182: `scanFile` in a .d.mts and in a docs/workorders/*/probes script refused the function's real file).
const HOLDS_NO_DEFS = /\.d\.[cm]?ts$|^docs\/(?:.*\/)?probes\//;
export const holdsNoDefs = (rel) => HOLDS_NO_DEFS.test(rel);
/** The keys the daemon's index is asked by: a statement's hash is its own key, an element shape's id and a definition's name are prefixed. */
export const shapeKey = (id) => `shape:${id}`;
export const defKey = (name) => `def:${name}`;
// What a text holds, with its marked one-offs left out: all the law ever compares.
export function shapesOfText(text, rel) {
    if (GENERATED.test(text.slice(0, 400)))
        return { shapes: [], st: [], defs: [] };
    const off = oneOffLines(text);
    const ext = extname(rel);
    const open = (list) => list.filter(([, line]) => !off.has(line));
    return { shapes: distinct(shapesOf(text, ext).filter((s) => !off.has(s.line))), st: open(fingerprint(text, ext)), defs: holdsNoDefs(rel) ? [] : open(definesOf(text, ext)) };
}
// sha256 of the root, the first 12 digits: the names the kit has already written (hash.mts keeps sha1 for its ids).
const fileOf = (root) => tmpKeyed('claude-packs-repo-', root, '.json');
const isEntry = (v) => typeof v === 'object' && v !== null && 'm' in v && 's' in v
    && Array.isArray(v.shapes) && Array.isArray(v.st) && Array.isArray(v.defs);
// What this process last held of each checkout's index (by its file): the next call starts from it, not from the file (KWB-201: reading the
// whole index back cost a worker 30 ms a write). A caller's skip list is part of the key, as the index it keeps holds only what that list leaves.
const held = new Map();
export function repoIndex(root, skip, layout = {}) {
    const file = fileOf(root);
    const skips = skip.join('\0');
    const mine = held.get(file);
    const old = mine && mine.skips === skips ? mine.index : readJson(file) ?? {}; // the first call builds it
    const now = {};
    let changed = false;
    for (const rel of codeFiles(root, skip, EXTS).filter((f) => !isContent(f, layout))) {
        const st = statSync(join(root, rel));
        const had = old[rel];
        if (isEntry(had) && had.m === st.mtimeMs && had.s === st.size) {
            now[rel] = had;
            continue;
        }
        const read = shapesOfText(readText(join(root, rel)) ?? '', rel);
        now[rel] = { m: st.mtimeMs, s: st.size, shapes: read.shapes.map((x) => [x.id, x.line, x.what]), st: read.st, defs: read.defs };
        changed = true;
    }
    if (changed || Object.keys(old).length !== Object.keys(now).length)
        writeJson(file, now); // an index that cannot be kept is built again; one that did not change is not written
    held.set(file, { skips, index: now });
    return now;
}
