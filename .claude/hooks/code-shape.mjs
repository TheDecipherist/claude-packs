#!/usr/bin/env node
// PreToolUse (Write|Edit|MultiEdit|NotebookEdit|Bash): code stays small in every direction, not only in lines per file. Measured on a real repo: 21% of
// code lines held two or more statements, so a file "under 300 lines" was 500, and one function held 140 statements in 70 lines. A write is refused when it adds
// a line too wide or packed, a function too long, or a function with too many parameters. What already stands is judged only if it gets worse.
// `layout.json` "guards": { "codeShape": { "maxLineChars", "maxStatementsPerLine", "maxFunctionStatements", "maxParameters" } } changes a limit.
// `--selftest` proves it.
import { extname } from 'node:path';
import { statementsOf } from './lib/code-shapes.mjs';
import { isContent } from './lib/content.mjs';
import { TESTS } from './lib/elements.mjs';
import { functionsOf } from './lib/function-shapes.mjs';
import { matchesAny } from './lib/glob.mjs';
import { languageOf } from './lib/languages.mjs';
import { readLayout } from './lib/layout.mjs';
import { claudeRoot } from './lib/project.mjs';
import { oneOffLines } from './lib/repo-index.mjs';
import { bashOf, editOf, runHook, scratchProject, verdicts, writeOf } from './lib/selftest.mjs';
import { judgeEvent } from './lib/writes.mjs';
import { asHook, isMain, projectRoot } from './lib/hook-log.mjs';
import { fileURLToPath } from 'node:url';


const LIMITS = { maxLineChars: 120, maxStatementsPerLine: 2, maxFunctionStatements: 50, maxParameters: 6 };
const GENERATED = /\b(?:auto-?generated|generated by|do not edit|@generated)\b/i;

// Lines this write adds, by number: a line that was already there is not its fault.
function addedLines(before, after) {
  const left = before.split('\n').reduce((m, l) => m.set(l, (m.get(l) ?? 0) + 1), new Map());
  return after.split('\n').flatMap((l, i) => { const n = left.get(l) ?? 0; left.set(l, n - 1); return n > 0 ? [] : [i + 1]; });
}

// Every line at fault at once: one a refusal cost a whole resend for each, the largest cost the kit added on the MPX 500 (37 of its 132 refusals).
function lineFaults(lang, text, added, off, limits) {
  const code = lang.blank(text).split('\n');
  const perLine = statementsOf(text, lang).reduce((m, s) => m.set(s.line, (m.get(s.line) ?? 0) + 1), new Map());
  const faults = [];
  for (const n of added.filter((x) => !off.has(x))) {
    const width = code[n - 1]?.trimEnd().length ?? 0;
    if (width > limits.maxLineChars) faults.push(`line ${n} is ${width} columns of code (limit ${limits.maxLineChars}). Break it where it reads.`);
    if ((perLine.get(n) ?? 0) > limits.maxStatementsPerLine) faults.push(`line ${n} holds ${perLine.get(n)} statements. One statement a line: a diff, a breakpoint and a coverage line then mean something, and the file's size is true.`);
  }
  return faults;
}

function functionFault(before, after, off, limits) {
  const was = new Map(before.map((f) => [f.name, f]));
  for (const f of after.filter((x) => !off.has(x.line))) {
    const old = was.get(f.name);
    if (f.statements > limits.maxFunctionStatements && f.statements > (old?.statements ?? 0)) return `${f.name} (line ${f.line}) holds ${f.statements} statements (limit ${limits.maxFunctionStatements}). A function that does many things cannot be tested in parts: split it by what it does.`;
    if (f.params > limits.maxParameters && f.params > (old?.params ?? 0)) return `${f.name} (line ${f.line}) takes ${f.params} parameters (limit ${limits.maxParameters}). Pass one struct or object: positional arguments of one type get swapped and still compile.`;
  }
  return null;
}

function judgeWrite(w, rel) {
  const ext = extname(w.path);
  const lang = languageOf(ext);
  if (!lang || w.op === 'delete' || w.after === null || w.after === undefined || matchesAny(rel, TESTS) || GENERATED.test(w.after.slice(0, 400))) return null;
  const layout = readLayout(claudeRoot(projectRoot(), w.path, process.cwd()));
  const limits = { ...LIMITS, ...(layout.guards?.codeShape ?? {}) };
  if (matchesAny(rel, layout.guards?.codeShape?.exclude ?? []) || isContent(rel, layout)) return null;
  const before = w.before ?? '';
  const off = oneOffLines(w.after);
  const faults = [...lineFaults(lang, w.after, addedLines(before, w.after), off, limits), functionFault(functionsOf(before, ext), functionsOf(w.after, ext), off, limits)].filter(Boolean);
  return faults.length ? `${faults.join('\n')}\nIf one truly must stay, say so above it: \`one-off: <reason>\`.\n` : null;
}

const main = (text) => judgeEvent(text, { name: 'code-shape', write: judgeWrite }, process);

function selftest() {
  const hook = fileURLToPath(import.meta.url);
  const body = (n) => Array.from({ length: n }, (_, i) => `  total = total + step(${i});\n`).join('');
  const long = `void big() {\n${body(60)}}\n`;
  const dir = scratchProject({ 'src/old.cpp': `void old() {\n${body(55)}}\n`, 'src/packed.h': 'void p() { a(); b(); c(); d(); }\n', 'kept/x.cpp': '// x\n', '.claude/layout.json': JSON.stringify({ guards: { codeShape: { exclude: ['kept/**'] } } }) });
  const w = (file, content) => runHook(hook, dir, writeOf(`${dir}/${file}`, content)).status;
  const wide = `int x = ${'a + '.repeat(40)}b;\n`;
  return verdicts('code-shape', [
    ['a function over the limit', w('src/a.cpp', long), 2],
    ['the same in python', w('src/a.py', `def big(rows):\n${Array.from({ length: 60 }, (_, i) => `    total = step(${i})\n`).join('')}`), 2],
    ['too many parameters', w('src/b.cpp', 'void f(int a, int b, int c, int d, int e, int f, int g) {\n  run(a);\n}\n'), 2],
    ['a self parameter is not counted', w('src/b.py', 'def f(self, a, b, c, d, e, g):\n    run(a)\n'), 0],
    ['packed statements', w('src/c.cpp', 'void f() {\n  a(); b(); c();\n}\n'), 2],
    ['a Python set comprehension is one statement (KF-14)', w('src/s.py', 'left = {keep(row) for row in rows} - {drop(row) for row in rows}\n'), 0],
    ['a lambda in a list counts as in a call (KF-27)', w('src/l.cpp', 'void f()\n{\n    judge ("a", b, [&] { return g (1); }),\n    judge ("c", d, [&] { return g (2); }),\n}\n'), 0],
    ['a for header is one statement', w('src/d.cpp', 'void f() {\n  for (int i = 0; i < n; i++) total += v(i);\n}\n'), 0],
    ['a wide line', w('src/e.cpp', wide), 2],
    ['a wide comment is no code', w('src/f.cpp', `// ${'word '.repeat(50)}\nint x = 1;\n`), 0],
    ['an old long function, edited without growing', runHook(hook, dir, editOf(`${dir}/src/old.cpp`, 'step(3)', 'step(4)')).status, 0],
    ['an old long function that grows', runHook(hook, dir, editOf(`${dir}/src/old.cpp`, '  total = total + step(3);\n', '  total = total + step(3);\n  total = total + step(99);\n')).status, 2],
    ['an old packed line that is edited', runHook(hook, dir, editOf(`${dir}/src/packed.h`, 'void p()', 'void q()')).status, 2],
    ['a marked one-off', w('src/g.cpp', `// one-off: the table is generated by hand\n${wide}`), 0],
    ['a test file', w('tests/x_test.cpp', long), 0],
    ['an excluded folder', w('kept/y.cpp', long), 0],
    ['a tutorial sample in a content folder', w('articles/guide/y.cpp', long), 0],
    ['a blog route is code', w('src/app/blog/page.cpp', long), 2],
    ['a heredoc that adds a packed line', runHook(hook, dir, bashOf("cat > src/h.cpp <<'EOF'\nvoid f() { a(); b(); c(); }\nEOF", dir)).status, 2],
  ]);
}

export const hook = main; // run-hooks.mjs calls it with the event's text (KWB-24)
if (isMain(import.meta.url)) process.exit(process.argv.includes('--selftest') ? selftest() : await asHook('code-shape', main));
