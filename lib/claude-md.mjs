// Writes the generated layout section into the project's CLAUDE.md, between markers.
// Everything outside the markers is the user's and is never touched.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const START = '<!-- claude-packs:start -->';
const END = '<!-- claude-packs:end -->';

function section(layout, packNames) {
  // Folders no kind points at are listed by purpose; the rest appear once, in the kinds list.
  const used = new Set(Object.values(layout.kinds ?? {}).map((k) => k.in));
  const folders = Object.entries(layout.folders)
    .filter(([name]) => !used.has(name) && name !== 'src')
    .sort(([, a], [, b]) => a.path.localeCompare(b.path))
    .map(([, f]) => `  - \`${f.path}/\`: ${f.purpose}`);
  return [
    START,
    '<!-- Generated by claude-packs from .claude/layout.json. Edit that file and run `npx claude-packs update`; edits here are replaced. -->',
    '## Project layout',
    '',
    '<constraints>',
    'Always do:',
    '- Put every kind of thing in its one place. The rules, checks and skills for it load only there:',
    ...kindLines(layout),
    ...(folders.length ? ['- The other folders:', ...folders] : []),
    '- Ask the user before inventing a new folder. A new folder goes into `.claude/layout.json` first.',
    '- When a hook, check or guard blocks work that is correct, stop and report its exact message. A blocking hook is a red check: fix the hook first, with a selftest, then continue.',
    '- When a command is refused or fails, the step fails loudly. Never report a refused write or a failed command as done.',
    '- claude-packs (`~/projects/claude-packs`) is the source of truth for every rule, check, hook and skill used to build synths. A fix to one of them, or a lesson that should hold in every synth, is made there with its test, committed, pushed and released as a new version, then taken in with `npx claude-packs update`, so every synth gets it. A project edits its installed copy only to try a fix before it goes into the kit.',
    '',
    'Never do:',
    '- Create source files outside these folders, or put a kind of thing anywhere but its place. The folder-law and placement-law hooks refuse both.',
    '- Put drawing code in audio or world folders, or audio and world logic in the painter or UI folders.',
    '- Edit files in `.claude/rules`, `.claude/checks` or `.claude/hooks` to get past a block. Fix the code, or ask the user to change the law.',
    '- Route around a block: no override variables, no writing through the shell after a refusal, no parking files in a scratchpad, no putting new code into an unrelated existing file.',
    '- Point at a document by line number. Cite a fixed anchor (`{#id}`) or a symbol name; lines move.',
    '</constraints>',
    '',
    ...commandLines(layout),
    `Installed packs: ${packNames.join(', ')}.`,
    END,
  ].join('\n');
}

function kindLines(layout) {
  return Object.values(layout.kinds ?? {}).map((k) => `  - ${k.what} → \`${layout.folders?.[k.in] ? `${layout.folders[k.in].path}/` : k.in}\``);
}

function commandLines(layout) {
  const entries = Object.entries(layout.commands ?? {});
  if (entries.length === 0) return [];
  return ['## Project commands', '', 'Skills and checks run these; use them, not the raw tools:', ...entries.map(([k, v]) => `- ${k}: \`${v}\``), ''];
}

export function writeClaudeMd(projectDir, layout, packNames) {
  const file = join(projectDir, 'CLAUDE.md');
  const block = section(layout, packNames);
  let text = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s !== -1 && e > s) text = text.slice(0, s) + block + text.slice(e + END.length);
  else text = `${text.trimEnd()}${text.trim() ? '\n\n' : ''}${block}\n`;
  writeFileSync(file, text);
}
